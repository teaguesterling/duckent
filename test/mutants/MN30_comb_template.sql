-- test/mutants/MN30_comb_template.sql
-- The registry's 'child' row loses its root equality -- the same defect MN14 plants in
-- tree_sql_children itself, but reached through the REGISTRY ROW instead of the macro. Task 1
-- froze every combinator's template into tree_catalog.combinators at INSERT time, and
-- tree_sql_comb (sql/07_match.sql) reads that frozen row rather than calling tree_sql_children
-- afresh -- so MN14 no longer reaches a compiled match through this surface at all (see its own
-- manifest row). This mutant plants the identical defect where a compiled match can still see
-- it: directly in the row the compiler actually reads. A kill proves the compiler consults the
-- TEMPLATE, not the macro that once produced it.
--
-- Hand-maintained, not generated by test/mutants/regen.py: this mutant edits a catalog ROW, not
-- a macro, so there is no `CREATE OR REPLACE MACRO` body for regen.py's extractor to copy. (Its
-- structural check still applies trivially: this file names no macro, so it cannot go stale
-- against one.)
UPDATE tree_catalog.combinators
   SET template = '{b}._parent = {a}._pre'
 WHERE op = 'child';
