#!/usr/bin/env python3
"""Import astcss-eval's accepted pairs and generate the corpus suites.

    python3 test/import_astcss_eval.py          # from the repo root

Reads `~/Projects/astcss-eval/pairs/accepted-b*.jsonl` (108 rows at batch b3) and the hand
corpus `test/corpus/selectors.tsv`, and writes five files, one per `write_*` function below:

  test/corpus/astcss_eval.jsonl        the imported rows, with both duckent spellings attached
  test/corpus/aliases.tsv              alias -> the semantic types it selects on our fixtures
  test/sql/40_corpus.test              P22: the two spellings of one selector agree
  test/sql/41_differential_sitting_duck.test   frozen references, no sitting_duck needed
  test/sql/41b_live_sitting_duck.test          the same, against today's sitting_duck

Everything it writes is deterministic and committed, so a re-run is a no-op and a diff is a real
change. Needs `duckdb`; needs sitting_duck loadable only for `aliases.tsv`.

A reference is never edited. Where our answer and a frozen reference disagree, the adjudication
goes in FINDINGS.md ("M2 differential adjudications") and the row is listed in DIVERGENT below,
which turns its frozen-reference assertion into a commented no-op naming the reason.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "test"))
import css_parser
import run as runner

ASTCSS = os.path.expanduser("~/Projects/astcss-eval")
PAIRS = os.path.join(ASTCSS, "pairs", "accepted-b*.jsonl")
CORPUS = os.path.join(ROOT, "test", "corpus")
SQL = os.path.join(ROOT, "test", "sql")

# astcss-eval's fixture names, our tree (and parquet) names, and the directory sitting_duck itself
# reads in 41b. `~` is expanded by DuckDB, so the generated SQL is not tied to one home directory.
TREE_OF = {"repo-small-py": "scripts", "py-variety": "py_variety"}
DIR_OF = {"repo-small-py": "~/Projects/astcss-eval/fixtures/repo-small-py/*.py",
          "py-variety": "~/Projects/astcss-eval/fixtures/py-variety/*.py"}

# Adjudicated in FINDINGS.md, "M2 differential adjudications". A row listed here keeps its
# reference verbatim in the jsonl and gains a `divergent:<reason>` tag; 41 comments its assertion
# out and says why, and 41b skips it (we already know the two engines disagree).
DIVERGENT = {
    "t1-p21": ("sd-type-prefix-match",
               "sitting_duck's bare type selector is a PREFIX match, so `lambda` also selects the "
               "`lambda_parameters` node update_test_names.py:247 (live: `lambd` selects both). A "
               "css type selector is equality on the node type, so duckent's 2 rows are right and "
               "the reference's 3 are the upstream bug."),
}

# 41b talks to the installed sitting_duck, which regressed on issue #127: every selector whose
# chain has a combinator returns 0 rows there, including the 31 rows whose frozen references were
# captured on a build that had it fixed. The live suite therefore covers the single-compound rows
# (`:has`/`:not` included) and says so; 41 covers all 108 offline.
COMBINATORS = ("desc", "child", "next", "after")

GENERATED = ("# GENERATED by test/import_astcss_eval.py from test/corpus/selectors.tsv and\n"
             "# ~/Projects/astcss-eval/pairs/accepted-b*.jsonl -- do not edit by hand.\n")

TREE_DDL = """CALL tree_ddl_create('main', '{tree}', tree_spec(tree_shape(
  root := 'file_path', "order" := 'node_id', level := 'depth', size := 'descendant_count',
  semantic := tree_semantic(type := 'type', id := 'name', classes := 'css_classes',
    element := 'is_element', pseudo := [{{name: 'def', body: '(flags & 6) = 6'}}])),
  source := 'read_parquet(''test/data/{tree}.parquet'')'));"""


# --- reading the two corpora --------------------------------------------------------------

def sql_text(s):
    """`s` as a single-quoted SQL literal body (the quotes are written by the caller)."""
    return s.replace("'", "''")


def top_level_combinator(css):
    """Whether the selector's own chain has more than one step. A step inside `:has`/`:not` is a
    test on one row, not a chain, so it does not count."""
    rows = css_parser.parse(css)
    root = next(r["node_id"] for r in rows if r["parent_id"] is None)
    return any(r["kind"] == "step" and r["parent_id"] == root and r["op"] in COMBINATORS
               for r in rows)


def read_selectors_tsv():
    """The hand corpus: dicts with id, treeql (a `tree_steps([...])` literal), css, fixture, tags."""
    with open(os.path.join(CORPUS, "selectors.tsv")) as f:
        head = f.readline().rstrip("\n").split("\t")
        rows = []
        for line in f:
            if line.strip():
                row = dict(zip(head, line.rstrip("\n").split("\t")))
                row["tags"] = row["tags"].split()
                rows.append(row)
    return rows


def read_astcss_pairs(session):
    """astcss-eval's accepted pairs, in file order, each with both duckent spellings attached:

    `treeql_ir` is the IR the runner's css parser builds, as a `[...]::TREE_SELECTOR` literal --
    not a `tree_steps([...])` literal, which cannot express two classes on one compound -- and
    `treeql` is that IR printed back as canonical TREEQL by the catalog's own printer.
    """
    rows = []
    for path in sorted(glob.glob(PAIRS)):
        for line in open(path):
            if not line.strip():
                continue
            src = json.loads(line)
            ir = css_parser.to_sql(css_parser.parse(src["css"]))
            treeql = session.con.execute("SELECT tree_selector_to_treeql(%s)" % ir).fetchone()[0]
            tags = list(src["tags"])
            if src["id"] in DIVERGENT:
                tags.append("divergent:" + DIVERGENT[src["id"]][0])
            if "astcss_eval" not in tags:
                tags.append("astcss_eval")
            rows.append({"id": src["id"], "css": src["css"], "fixture": TREE_OF[src["fixture"]],
                         "sd_fixture": src["fixture"], "tags": tags,
                         "treeql_ir": ir, "treeql": treeql, "reference": src["reference"]})
    return rows


# --- the five generated files -------------------------------------------------------------

def write_astcss_jsonl(rows):
    """test/corpus/astcss_eval.jsonl -- one imported row per line, references verbatim."""
    path = os.path.join(CORPUS, "astcss_eval.jsonl")
    with open(path, "w") as f:
        for r in rows:
            f.write(json.dumps({k: r[k] for k in
                                ("id", "css", "fixture", "tags", "treeql_ir", "treeql", "reference")},
                               sort_keys=False) + "\n")
    return path


def write_aliases_tsv(session):
    """test/corpus/aliases.tsv -- for each corpus alias, the sitting_duck semantic types it
    selects on our three fixtures, and how many rows carry it. Documentation for the reader of a
    corpus row: `.fn` is not a type name, it is this set of semantic types."""
    session.con.execute("LOAD sitting_duck")
    trees = ("app", "scripts", "py_variety")
    union = " UNION ALL ".join(
        "SELECT '%s' AS fixture, unnest(css_classes) AS alias, semantic_type "
        "FROM read_parquet('test/data/%s.parquet')" % (t, t) for t in trees)
    counts = "".join(", count(*) FILTER (WHERE fixture = '%s') AS %s" % (t, t) for t in trees)
    rows = session.con.execute(
        "SELECT alias, list_aggregate(list_sort(list(DISTINCT semantic_type_to_string(semantic_type))), "
        "'string_agg', ',') AS semantic_types%s FROM (%s) GROUP BY alias ORDER BY alias"
        % (counts, union)).fetchall()
    path = os.path.join(CORPUS, "aliases.tsv")
    with open(path, "w") as f:
        f.write("alias\tsemantic_types\t" + "\t".join(trees) + "\n")
        for r in rows:
            f.write("\t".join(str(v) for v in r) + "\n")
    return path


def write_40_corpus(hand, astcss):
    """test/sql/40_corpus.test -- P22: one selector, two spellings, the same rows.

    Per corpus row two records: the matched `node_id` lists agree, and the TREEQL the printer
    renders from the IR agrees with the TREEQL `tree_explain` reports for the css text. A row
    that matches nothing fails on its own: `list()` over no rows is NULL, and `NULL = NULL` is
    NULL, which is not `true`. So every record here is discriminating without a count to maintain.
    """
    out = ["# name: test/sql/40_corpus.test\n",
           "# description: P22 -- the treeql and the css spelling of one selector match the same\n",
           "# rows and print as the same canonical TREEQL, over the whole corpus\n",
           "#\n",
           "# The `tree_steps([...])` literals are the hand corpus (test/corpus/selectors.tsv); the\n",
           "# `[...]::TREE_SELECTOR` literals are the IR the runner's css parser built for the\n",
           "# astcss-eval row, stored in test/corpus/astcss_eval.jsonl as `treeql_ir`.\n#\n",
           GENERATED, "\n"]
    out += _tree_ddl_records(("app", "scripts", "py_variety"))
    out.append("# " + "-" * 86 + "\n# the hand corpus: test/corpus/selectors.tsv\n# "
               + "-" * 86 + "\n\n")
    for r in hand:
        out += _p22_records(r["id"], r["fixture"], r["treeql"], r["css"], r["tags"])
    out.append("# " + "-" * 86 + "\n# astcss-eval accepted pairs: test/corpus/astcss_eval.jsonl\n# "
               + "-" * 86 + "\n\n")
    for r in astcss:
        out += _p22_records(r["id"], r["fixture"], r["treeql_ir"], r["css"], r["tags"])
    return _write(os.path.join(SQL, "40_corpus.test"), out)


def write_41_differential(astcss):
    """test/sql/41_differential_sitting_duck.test -- the frozen references, needing no sitting_duck.

    Two records per row: the node keys we select, as a list ordered exactly the way astcss-eval
    ordered them (so a failure prints both lists side by side), and the sha256 of that list joined
    with commas, which is the recipe astcss-eval's verify.py used and therefore proves the keys.

    Both read `SELECT DISTINCT file_path, node_id`: duckent's match emits one row per full-pattern
    embedding (core design 6.3), sitting_duck's emits the subject set, so a node reached by two
    witnesses -- `.import ~ .class` with three preceding imports -- is three rows here and one
    there. The set is what the two engines are meant to agree on (M2 design 8); the multiplicity
    is duckent's contract, not a divergence. FINDINGS.md records which rows this touches.
    """
    out = ["# name: test/sql/41_differential_sitting_duck.test\n",
           "# description: every sitting_duck_supported astcss-eval row against its FROZEN\n",
           "# reference (node keys and sha256). No sitting_duck: the fixtures carry css_classes,\n",
           "# is_element and params, so these run on the parquet alone. 41b is the live twin.\n",
           "#\n",
           "# References are copied verbatim from ~/Projects/astcss-eval/pairs/accepted-b*.jsonl\n",
           "# and are never edited. A row we adjudicated against upstream is commented out below\n",
           "# with its reason; see FINDINGS.md, \"M2 differential adjudications\".\n#\n",
           GENERATED, "\n"]
    out += _tree_ddl_records(("scripts", "py_variety"))
    for r in astcss:
        out += _reference_records(r)
    return _write(os.path.join(SQL, "41_differential_sitting_duck.test"), out)


def write_41b_live(astcss):
    """test/sql/41b_live_sitting_duck.test -- the same rows against today's sitting_duck.

    sitting_duck's own source, not our parquet: `ast_select_from` cannot read the parquet at all
    (it converts `semantic_type` to UINT8 and ours is stored as UTINYINT), so the live side reads
    `read_ast('<fixture dir>/*.py')` with `file_path` cut back to the basename, which is the key
    shape both sides use. Each row is one record comparing the key sets with EXCEPT both ways.
    """
    chained = [r for r in astcss if r["id"] not in DIVERGENT and top_level_combinator(r["css"])]
    skipped_ids = {r["id"] for r in chained} | set(DIVERGENT)
    skipped = [r for r in astcss if r["id"] in skipped_ids]
    live = [r for r in astcss if r["id"] not in skipped_ids]
    out = ["# name: test/sql/41b_live_sitting_duck.test\n",
           "# description: duckent's match against the INSTALLED sitting_duck, on sitting_duck's\n",
           "# own read_ast rows, read from ~/Projects/astcss-eval/fixtures. That checkout has to be\n",
           "# there: the runner can skip a file for a missing extension, not for a missing directory.\n",
           "#\n",
           "# %d of %d rows run here. The other %d are skipped for a reason the corpus records,\n"
           % (len(live), len(astcss), len(skipped)),
           "# not for convenience: %d have a combinator in their chain, which the installed engine\n"
           % len(chained),
           "# returns 0 rows for (sitting_duck #127 -- the frozen references in 41 were captured on\n",
           "# a build that had it fixed, so 41 still holds them), and %d adjudicated divergent.\n#\n"
           % len(DIVERGENT),
           GENERATED,
           "\nrequire sitting_duck\n\nstatement ok\nLOAD sitting_duck;\n\n"]
    for fx in sorted({r["sd_fixture"] for r in live}):
        out.append("statement ok\nCREATE TABLE sd_%s AS SELECT * REPLACE "
                   "(regexp_replace(file_path, '.*/', '') AS file_path) FROM read_ast('%s');\n\n"
                   % (TREE_OF[fx], DIR_OF[fx]))
    out += _tree_ddl_records(("scripts", "py_variety"))
    for r in live:
        out += _live_records(r)
    out.append("# skipped above, and why:\n")
    for r in skipped:
        why = ("divergent:" + DIVERGENT[r["id"]][0]) if r["id"] in DIVERGENT else "sitting_duck #127"
        out.append("#   %-8s %-34s %s\n" % (r["id"], r["css"], why))
    return _write(os.path.join(SQL, "41b_live_sitting_duck.test"), out)


# --- record templates ---------------------------------------------------------------------

def _write(path, chunks):
    with open(path, "w") as f:
        f.write("".join(chunks))
    return path


def _tree_ddl_records(trees):
    """The corpus trees a file uses, created once at its top. ATTR is left at the default `*`, so
    `name` and `params` are projected columns an `[attr]` clause can compare."""
    out = ["# The corpus trees. CLASSES, ELEMENT and `params` are columns test/gen_fixtures.py\n"
           "# derived from sitting_duck at fixture time, so nothing here needs the extension.\n\n"]
    for tree in trees:
        out.append("statement ok\n" + TREE_DDL.format(tree=tree) + "\n\n")
    return out


def _p22_records(cid, tree, treeql, css, tags):
    return ["# %s  %s  [%s]  %s\n" % (cid, css, tree, " ".join(tags)),
            "query I\nSELECT (SELECT list(node_id ORDER BY node_id) FROM tree_match('main', '%s', %s))\n"
            "     = (SELECT list(node_id ORDER BY node_id) FROM tree_match('main', '%s', '%s', language := 'css'));\n"
            "----\ntrue\n\n" % (tree, treeql, tree, sql_text(css)),
            "query I\nSELECT tree_selector_to_treeql(%s)\n"
            "     = (tree_explain('main', '%s', '%s', language := 'css')).treeql;\n----\ntrue\n\n"
            % (treeql, tree, sql_text(css))]


def _keys_from_match(tree, css):
    """The node keys of a css match, as astcss-eval spells and orders them."""
    return ("FROM (SELECT DISTINCT file_path, node_id\n"
            "      FROM tree_match('main', '%s', '%s', language := 'css'))" % (tree, sql_text(css)))


def _reference_records(r):
    head = "# %s  %s  [%s]  %d nodes\n" % (r["id"], r["css"], r["fixture"], r["reference"]["count"])
    if r["id"] in DIVERGENT:
        reason, why = DIVERGENT[r["id"]]
        body = "".join("#   " + l + "\n" for l in _wrap(why, 92))
        return [head, "# NOT ASSERTED -- divergent:%s (FINDINGS.md, M2 differential adjudications)\n"
                % reason, body, "\n"]
    nodes = "[" + ", ".join(r["reference"]["nodes"]) + "]"
    return [head,
            "query I\nSELECT list(regexp_replace(file_path, '.*/', '') || ':' || node_id "
            "ORDER BY file_path, node_id)\n%s;\n----\n%s\n\n" % (_keys_from_match(r["fixture"], r["css"]), nodes),
            "query I\nSELECT sha256(string_agg(regexp_replace(file_path, '.*/', '') || ':' || node_id, ',' "
            "ORDER BY file_path, node_id))\n%s;\n----\n%s\n\n"
            % (_keys_from_match(r["fixture"], r["css"]), r["reference"]["sha256"])]


def _live_records(r):
    tbl, tree = "sd_" + r["fixture"], r["fixture"]
    # our scripts.parquet keeps the `scripts/` directory read_ast saw; both sides are cut back to
    # the basename, which is the key shape astcss-eval's references use as well
    ours = ("SELECT DISTINCT regexp_replace(file_path, '.*/', '') AS f, node_id "
            "FROM tree_match('main', '%s', '%s', language := 'css')" % (tree, sql_text(r["css"])))
    theirs = ("SELECT regexp_replace(file_path, '.*/', '') AS f, node_id "
              "FROM ast_select_from('%s', '%s')" % (tbl, sql_text(r["css"])))
    return ["# %s  %s  [%s]\n" % (r["id"], r["css"], tree),
            "query II\nSELECT (SELECT count(*) FROM ((%s) EXCEPT (%s))),\n"
            "       (SELECT count(*) FROM ((%s) EXCEPT (%s)));\n----\n0\t0\n\n"
            % (ours, theirs, theirs, ours)]


def _wrap(text, width):
    lines, cur = [], ""
    for word in text.split():
        if cur and len(cur) + 1 + len(word) > width:
            lines.append(cur); cur = word
        else:
            cur = (cur + " " + word).strip()
    if cur:
        lines.append(cur)
    return lines


def main():
    os.chdir(ROOT)
    session = runner.Session()
    hand = read_selectors_tsv()
    astcss = read_astcss_pairs(session)
    # aliases.tsv first: it is the one file that needs sitting_duck, so a machine without the
    # extension fails before anything has been half-written
    written = [write_aliases_tsv(session), write_astcss_jsonl(astcss),
               write_40_corpus(hand, astcss), write_41_differential(astcss),
               write_41b_live(astcss)]
    print("hand rows: %d   astcss rows: %d (%d divergent)"
          % (len(hand), len(astcss), len(DIVERGENT)))
    for path in written:
        print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
