def _keys_from_match(tree, css):
    """The node keys of a css match, as astcss-eval spells and orders them."""
    return ("FROM (SELECT DISTINCT file_path, node_id\n"
            "      FROM tree_match('main', '%s', '%s', language := 'css'))" % (tree, sql_text(css)))


def _reference_records(r):
    head = "# %s  %s  [%s]  %d nodes\n" % (r["id"], r["css"], r["fixture"], r["reference"]["count"])
    if r["id"] in DIVERGENT:
        reason, why = DIVERGENT[r["id"]]
        body = "".join("#   " + l + "\n" for l in _wrap(why, 92))
        return [head, "# NOT ASSERTED -- divergent:%s (FINDINGS.md, M2 differential adjudications)\n"
                % reason, body, "\n"]
    nodes = "[" + ", ".join(r["reference"]["nodes"]) + "]"
    return [head,
            "query I\nSELECT list(regexp_replace(file_path, '.*/', '') || ':' || node_id "
            "ORDER BY file_path, node_id)\n%s;\n----\n%s\n\n" % (_keys_from_match(r["fixture"], r["css"]), nodes),
            "query I\nSELECT sha256(string_agg(regexp_replace(file_path, '.*/', '') || ':' || node_id, ',' "
            "ORDER BY file_path, node_id))\n%s;\n----\n%s\n\n"
            % (_keys_from_match(r["fixture"], r["css"]), r["reference"]["sha256"])]


def _live_records(r):
    tbl, tree = "sd_" + r["fixture"], r["fixture"]
    # our scripts.parquet keeps the `scripts/` directory read_ast saw; both sides are cut back to
    # the basename, which is the key shape astcss-eval's references use as well
    ours = ("SELECT DISTINCT regexp_replace(file_path, '.*/', '') AS f, node_id "
            "FROM tree_match('main', '%s', '%s', language := 'css')" % (tree, sql_text(r["css"])))
    theirs = ("SELECT regexp_replace(file_path, '.*/', '') AS f, node_id "
              "FROM ast_select_from('%s', '%s')" % (tbl, sql_text(r["css"])))
    return ["# %s  %s  [%s]\n" % (r["id"], r["css"], tree),
            "query II\nSELECT (SELECT count(*) FROM ((%s) EXCEPT (%s))),\n"
            "       (SELECT count(*) FROM ((%s) EXCEPT (%s)));\n----\n0\t0\n\n"
            % (ours, theirs, theirs, ours)]


def _wrap(text, width):
    lines, cur = [], ""
    for word in text.split():
        if cur and len(cur) + 1 + len(word) > width:
            lines.append(cur); cur = word
        else:
            cur = (cur + " " + word).strip()
    if cur:
        lines.append(cur)
    return lines


