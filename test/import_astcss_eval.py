           "# References are copied verbatim from ~/Projects/astcss-eval/pairs/accepted-b*.jsonl\n",
           "# and are never edited. A row we adjudicated against upstream is commented out below\n",
           "# with its reason; see FINDINGS.md, \"M2 differential adjudications\".\n#\n",
