# --- reading the two corpora --------------------------------------------------------------

def sql_text(s):
    """`s` as a single-quoted SQL literal body (the quotes are written by the caller)."""
    return s.replace("'", "''")


def top_level_combinator(css):
    """Whether the selector's own chain has more than one step. A step inside `:has`/`:not` is a
    test on one row, not a chain, so it does not count."""
    rows = css_parser.parse(css)
    root = next(r["node_id"] for r in rows if r["parent_id"] is None)
    return any(r["kind"] == "step" and r["parent_id"] == root and r["op"] in COMBINATORS
               for r in rows)


def read_selectors_tsv():
    """The hand corpus: dicts with id, treeql (a `tree_steps([...])` literal), css, fixture, tags."""
    with open(os.path.join(CORPUS, "selectors.tsv")) as f:
        head = f.readline().rstrip("\n").split("\t")
        rows = []
        for line in f:
            if line.strip():
                row = dict(zip(head, line.rstrip("\n").split("\t")))
                row["tags"] = row["tags"].split()
                rows.append(row)
    return rows


def read_astcss_pairs(session):
    """astcss-eval's accepted pairs, in file order, each with both duckent spellings attached:

    `treeql_ir` is the IR the runner's css parser builds, as a `[...]::TREE_SELECTOR` literal --
    not a `tree_steps([...])` literal, which cannot express two classes on one compound -- and
    `treeql` is that IR printed back as canonical TREEQL by the catalog's own printer.
    """
    rows = []
    for path in sorted(glob.glob(PAIRS)):
        for line in open(path):
            if not line.strip():
                continue
            src = json.loads(line)
            ir = css_parser.to_sql(css_parser.parse(src["css"]))
            treeql = session.con.execute("SELECT tree_selector_to_treeql(%s)" % ir).fetchone()[0]
            tags = list(src["tags"])
            if src["id"] in DIVERGENT:
                tags.append("divergent:" + DIVERGENT[src["id"]][0])
            if "astcss_eval" not in tags:
                tags.append("astcss_eval")
            rows.append({"id": src["id"], "css": src["css"], "fixture": TREE_OF[src["fixture"]],
                         "sd_fixture": src["fixture"], "tags": tags,
                         "treeql_ir": ir, "treeql": treeql, "reference": src["reference"]})
    return rows


# --- the five generated files -------------------------------------------------------------

def write_astcss_jsonl(rows):
    """test/corpus/astcss_eval.jsonl -- one imported row per line, references verbatim."""
    path = os.path.join(CORPUS, "astcss_eval.jsonl")
    with open(path, "w") as f:
        for r in rows:
            f.write(json.dumps({k: r[k] for k in
                                ("id", "css", "fixture", "tags", "treeql_ir", "treeql", "reference")},
                               sort_keys=False) + "\n")
    return path


def write_aliases_tsv(session):
    """test/corpus/aliases.tsv -- for each corpus alias, the sitting_duck semantic types it
    selects on our three fixtures, and how many rows carry it. Documentation for the reader of a
    corpus row: `.fn` is not a type name, it is this set of semantic types."""
    session.con.execute("LOAD sitting_duck")
    trees = ("app", "scripts", "py_variety")
    union = " UNION ALL ".join(
        "SELECT '%s' AS fixture, unnest(css_classes) AS alias, semantic_type "
        "FROM read_parquet('test/data/%s.parquet')" % (t, t) for t in trees)
    counts = "".join(", count(*) FILTER (WHERE fixture = '%s') AS %s" % (t, t) for t in trees)
    rows = session.con.execute(
        "SELECT alias, list_aggregate(list_sort(list(DISTINCT semantic_type_to_string(semantic_type))), "
        "'string_agg', ',') AS semantic_types%s FROM (%s) GROUP BY alias ORDER BY alias"
        % (counts, union)).fetchall()
    path = os.path.join(CORPUS, "aliases.tsv")
    with open(path, "w") as f:
        f.write("alias\tsemantic_types\t" + "\t".join(trees) + "\n")
        for r in rows:
            f.write("\t".join(str(v) for v in r) + "\n")
    return path


