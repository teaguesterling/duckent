def write_41b_live(astcss):
    """test/sql/41b_live_sitting_duck.test -- the same rows against today's sitting_duck.

    sitting_duck's own source, not our parquet: `ast_select_from` cannot read the parquet at all
    (it converts `semantic_type` to UINT8 and ours is stored as UTINYINT), so the live side reads
    `read_ast('<fixture dir>/*.py')` with `file_path` cut back to the basename, which is the key
    shape both sides use. Each row is one record comparing the key sets with EXCEPT both ways.
    """
    # TODO(sd#127): drop this skip when upstream fixes combinator steps
    chained = [r for r in astcss if r["id"] not in DIVERGENT and top_level_combinator(r["css"])]
    skipped_ids = {r["id"] for r in chained} | set(DIVERGENT)
    skipped = [r for r in astcss if r["id"] in skipped_ids]
    live = [r for r in astcss if r["id"] not in skipped_ids]
    out = ["# name: test/sql/41b_live_sitting_duck.test\n",
           "# description: duckent's match against the INSTALLED sitting_duck, on sitting_duck's\n",
           "# own read_ast rows, read from ~/Projects/astcss-eval/fixtures. That checkout has to be\n",
           "# there: the runner can skip a file for a missing extension, not for a missing directory.\n",
           "#\n",
           "# %d of %d rows run here. The other %d are skipped for a reason the corpus records,\n"
           % (len(live), len(astcss), len(skipped)),
           "# not for convenience: %d have a combinator in their chain, which the installed engine\n"
           % len(chained),
           "# returns 0 rows for (sitting_duck #127 -- the frozen references in 41 were captured on\n",
           "# a build that had it fixed, so 41 still holds them), and %d adjudicated divergent.\n"
           % len(DIVERGENT),
           "# TODO(sd#127): drop this skip when upstream fixes combinator steps\n#\n",
           GENERATED,
           "\nrequire sitting_duck\n\nstatement ok\nLOAD sitting_duck;\n\n"]
    for fx in sorted({r["sd_fixture"] for r in live}):
        out.append("statement ok\nCREATE TABLE sd_%s AS SELECT * REPLACE "
                   "(regexp_replace(file_path, '.*/', '') AS file_path) FROM read_ast('%s');\n\n"
                   % (TREE_OF[fx], DIR_OF[fx]))
    out += _tree_ddl_records(("scripts", "py_variety"))
    for r in live:
        out += _live_records(r)
    out.append("# skipped above, and why:\n")
    for r in skipped:
        why = ("divergent:" + DIVERGENT[r["id"]][0]) if r["id"] in DIVERGENT else "sitting_duck #127"
        out.append("#   %-8s %-34s %s\n" % (r["id"], r["css"], why))
    return _write(os.path.join(SQL, "41b_live_sitting_duck.test"), out)


def write_42_second_differential(hand):
    """test/sql/42_second_differential.test -- the declared O columns against the derived ones.

    The first differential (41) asks whether we agree with another engine. This one asks whether
    we agree with ourselves: `app_declared` takes SIZE, PARENT and CHILDREN from the parquet's own
    `descendant_count`, `parent_id` and `children_count`; `app_derived` declares none of them and
    lets the projection derive all three from (ROOT, ORDER, LEVEL). The S group, the source rows
    and the selector are identical, so no selector may be able to tell the two trees apart.

    app.parquet only (54 rows): the derived side is quadratic in the tree (tree_sql_size_expr is a
    correlated min over the projection), so running the corpus over scripts would cost minutes for
    no new coverage. Every one of astcss-eval's 108 rows targets `scripts` or `py_variety`, so the
    rows templated here are the hand corpus's own `app` rows -- which already cover a sibling
    combinator (c08) and nested :has/:not (c06, c07, c13), the two shapes that read the O columns
    hardest.

    Those rows are not on their own discriminating, which is why the file opens with a record
    comparing the two projections directly and follows it with SIZE_WITNESS: perturbing the
    declared SIZE by one moves no corpus answer on this fixture (see the comments in the file).
    """
    rows = [r for r in hand if r["fixture"] == "app"]
    out = ["# name: test/sql/42_second_differential.test\n",
           "# description: the second differential -- one tree whose SIZE, PARENT and CHILDREN are\n",
           "# declared columns against one that derives all three, over every app corpus selector.\n",
           "# Child, sibling and positional steps read PARENT; descendant steps and :has/:not read\n",
           "# SIZE. A derivation that disagreed with the parquet's own numbers would move rows.\n#\n",
           "# The selectors are the `app` rows of test/corpus/selectors.tsv, plus the one written\n",
           "# below for SIZE. astcss-eval's rows all target scripts/py_variety, so none of them is\n",
           "# templated here.\n#\n",
           GENERATED, "\n",
           "# The two trees. Same source, same S group; only the O group differs.\n\n",
           _app_ddl("app_declared",
                    ["size := 'descendant_count'", "parent := 'parent_id'",
                     "children := 'children_count'"], corpus_sem()),
           _app_ddl("app_derived", [], corpus_sem()),
           "# The two projections first, column for column. The selector records below are the\n"
           "# observable consequences, but they cannot be the whole claim: no selector reads\n"
           "# CHILDREN at all, and with ELEMENT declared the sibling and positional fragments\n"
           "# take the element-scan path rather than the O(1) pre/size arithmetic, so a wrong\n"
           "# SIZE or CHILDREN would be invisible to every one of them but the last.\n",
           "query III\nSELECT (SELECT count(*) FROM tree_project('main', 'app_declared'))\n"
           "     = (SELECT count(*) FROM tree_project('main', 'app_derived')),\n"
           "       (SELECT count(*) > 0 FROM tree_project('main', 'app_declared')),\n"
           "       (SELECT count(*) FROM tree_project('main', 'app_declared') d\n"
           "          JOIN tree_project('main', 'app_derived') v ON d._root = v._root AND d._pre = v._pre\n"
           "         WHERE d._size IS DISTINCT FROM v._size OR d._parent IS DISTINCT FROM v._parent\n"
           "            OR d._children IS DISTINCT FROM v._children);\n----\ntrue\ttrue\t0\n\n"]
    out += _same_keys_record(
        "# %s -- the one selector on this fixture whose answer reads SIZE: app.py:50 is the last\n"
        "# descendant of its `attribute`, so a subtree range one short of the declared size drops\n"
        "# it. Written here rather than in the corpus, which has no selector of that shape."
        % SIZE_WITNESS,
        _css_keys("app_declared", SIZE_WITNESS), _css_keys("app_derived", SIZE_WITNESS))
    for r in rows:
        head = "# %s  %s  %s" % (r["id"], r["css"], " ".join(r["tags"]))
        out += _same_keys_record(head, _css_keys("app_declared", r["css"]),
                                 _css_keys("app_derived", r["css"]))
    return _write(os.path.join(SQL, "42_second_differential.test"), out)


def write_43_representation(hand):
    """test/sql/43_representation.test -- P23: how a semantic is *represented* is not part of it.

    Three swaps over app.parquet, each leaving the semantics alone and changing only the spelling:

      (a) TYPE as a column (`type`) against TYPE as an expression (`lower(upper(type))`).
      (b) promotion: the same predicate as a PSEUDO body and as a CLASSES list built in the source.
      (c) ELEMENT as a column (`is_element`) against a macro over the same flag bit.

    (c) is the one that needs care. `is_element` is `is_construct(flags)` baked in at fixture time,
    and on all three fixtures that is exactly `(flags & 1) = 0` -- the bit sitting_duck sets on the
    anonymous token rows -- which is what `is_construct_stub` reproduces without the extension.
    `regexp_matches(type, '^[a-z_]')` is NOT that predicate: it also admits keyword tokens (`def`,
    `return`), which is a different element set, so the third tree is asserted to DISAGREE rather
    than to agree. Without that record (a) and (c) could both pass on a tree where ELEMENT was
    ignored altogether; with it, the file shows the predicate is load-bearing.
    """
    rows = [r for r in hand if r["fixture"] == "app"]
    out = ["# name: test/sql/43_representation.test\n",
           "# description: P23 -- a semantic is what it selects, not how it is spelled. TYPE as a\n",
           "# column vs as an expression, a PSEUDO body vs the same predicate promoted to CLASSES,\n",
           "# and ELEMENT as a column vs as a macro over the flag bit it was derived from.\n#\n",
           "# (a) and (c) run the `app` rows of test/corpus/selectors.tsv; (b) and the last record\n",
           "# of (c) are selectors written for those two claims, which the corpus has no row for.\n#\n",
           GENERATED, "\n",
           "# " + "-" * 86 + "\n# (a) TYPE: a column, or an expression over it\n# " + "-" * 86
           + "\n\n",
           _app_ddl("rep_col", SIZE_ONLY, corpus_sem()),
           _app_ddl("rep_expr", SIZE_ONLY, corpus_sem(type_expr="lower(upper(type))"))]
    for r in rows:
        head = "# %s  %s  %s" % (r["id"], r["css"], " ".join(r["tags"]))
        out += _same_keys_record(head, _css_keys("rep_col", r["css"]),
                                 _css_keys("rep_expr", r["css"]))
    out += ["# " + "-" * 86 + "\n# (b) promotion: one predicate as a PSEUDO body, and as a CLASSES"
            " list the source computes\n# " + "-" * 86 + "\n\n",
            _app_ddl("rep_pseudo", SIZE_ONLY,
                     "type := 'type', pseudo := [{name: 'def', body: '(flags & 6) = 6'}]"),
            _app_ddl("rep_class", SIZE_ONLY, "type := 'type', classes := 'cls'",
                     source="(SELECT *, CASE WHEN (flags & 6) = 6 THEN [''def''] ELSE [] END "
                            "AS cls FROM read_parquet(''test/data/app.parquet''))")]
    for sel, (lhs, rhs) in (("the bare pseudo-class",
                             ("[{pseudo: 'def'}]", "[{class: 'def'}]")),
                            ("a compound that also constrains TYPE",
                             ("[{type: 'function_definition', pseudo: 'def'}]",
                              "[{type: 'function_definition', class: 'def'}]"))):
        out += _same_keys_record("# %s" % sel,
                                 _treeql_keys("rep_pseudo", "tree_steps(%s)" % lhs),
                                 _treeql_keys("rep_class", "tree_steps(%s)" % rhs))
    out += ["# " + "-" * 86 + "\n# (c) ELEMENT: a column, or a macro over the flag bit it was"
            " derived from\n# " + "-" * 86 + "\n\n",
            "# `is_element` is is_construct(flags), frozen into the fixture. On app.parquet (and on\n"
            "# scripts and py_variety) that predicate is exactly this flag test, so the macro is a\n"
            "# second representation of the same element set, not an approximation of it.\n\n",
            "statement ok\nCREATE MACRO is_construct_stub(f) AS (f & 1) = 0;\n\n",
            _app_ddl("rep_elem_col", SIZE_ONLY, corpus_sem()),
            _app_ddl("rep_elem_stub", SIZE_ONLY,
                     corpus_sem(element_expr="is_construct_stub(flags)")),
            _app_ddl("rep_elem_expr", SIZE_ONLY,
                     corpus_sem(element_expr="regexp_matches(type, '^[a-z_]')"))]
    for r in rows:
        head = "# %s  %s  %s" % (r["id"], r["css"], " ".join(r["tags"]))
        out += _same_keys_record(head, _css_keys("rep_elem_col", r["css"]),
                                 _css_keys("rep_elem_stub", r["css"]))
    out += ["# A DIFFERENT predicate is a different tree, and this is what that looks like:\n"
            "# `^[a-z_]` admits the keyword tokens (`def`, `return`) that is_construct rejects, so\n"
            "# under it the `def` keyword is the first element child of a function_definition and\n"
            "# the name identifier no longer is. Not a bug -- the point of the section: ELEMENT is\n"
            "# read, so (a) and the records above are not passing on an ignored declaration.\n",
            "query II\nSELECT %s,\n       %s;\n----\n%s\n\n"
            % (_css_keys("rep_elem_col", ELEM_DIVERGES),
               _css_keys("rep_elem_expr", ELEM_DIVERGES), ELEM_DIVERGES_EXPECTED)]
    return _write(os.path.join(SQL, "43_representation.test"), out)


# --- record templates ---------------------------------------------------------------------

def _write(path, chunks):
    with open(path, "w") as f:
        f.write("".join(chunks))
    return path


def corpus_sem(type_expr="type", element_expr="is_element"):
    """The corpus S group, with TYPE and ELEMENT as parameters: 43 varies exactly those two and
    holds everything else fixed, so the S group has one spelling here."""
    return ("type := '%s', id := 'name', classes := 'css_classes',\n"
            "    element := '%s', pseudo := [{name: 'def', body: '(flags & 6) = 6'}]"
            % (sql_text(type_expr), sql_text(element_expr)))


def _tree_ddl_records(trees):
    """The corpus trees a file uses, created once at its top. ATTR is left at the default `*`, so
    `name` and `params` are projected columns an `[attr]` clause can compare."""
    out = ["# The corpus trees. CLASSES, ELEMENT and `params` are columns test/gen_fixtures.py\n"
           "# derived from sitting_duck at fixture time, so nothing here needs the extension.\n\n"]
    for tree in trees:
        out.append("statement ok\n" + TREE_DDL.format(tree=tree, sem=corpus_sem()) + "\n\n")
    return out


def _app_ddl(name, o_group, sem, source=APP_SOURCE):
    """One DDL record for a tree over app.parquet. 42 varies `o_group` (the declared O columns,
    a list of `size :=`/`parent :=`/`children :=` texts) and 43 varies `sem` and `source`;
    ROOT, ORDER and LEVEL are the same in every one of them."""
    o = ("  %s,\n" % ", ".join(o_group)) if o_group else ""
    return ("statement ok\nCALL tree_ddl_create('main', '%s', tree_spec(tree_shape(\n"
            "  root := 'file_path', \"order\" := 'node_id', level := 'depth',\n"
            "%s  semantic := tree_semantic(%s)),\n  source := '%s'));\n\n"
            % (name, o, sem, source))


